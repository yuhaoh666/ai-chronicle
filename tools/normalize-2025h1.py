src = json.load(open(SRC, encoding="utf-8"))
assert len(src) == len(S), (len(src), len(S))

changed_summary = changed_plain = 0
problems = []
for e in src:
    key = (e["date"], e["title"])
    assert key in S, key
    a, b, c = S[key]
    assert "→" not in a + b + c, key
    new = " → ".join([a, b, c])
    if new != e["summary"]:
        changed_summary += 1
    if len(new) > 200:
        problems.append(("summary>200", len(new), e["title"]))
    e["summary"] = new
    for con in e.get("concepts", []):
        k = (e["date"], con["term"])
        if k in PLAIN:
            if con["plain"] != PLAIN[k]:
                changed_plain += 1
            con["plain"] = PLAIN[k]

with open(DST, "w", encoding="utf-8") as f:
    json.dump(src, f, ensure_ascii=False, indent=2)

print("summary 改写条数:", changed_summary)
print("plain 改写条数:", changed_plain)
print("构建期问题:", problems)
print("写入:", DST, "总条数:", len(src))
